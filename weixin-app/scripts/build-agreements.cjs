// Canonical agreement text lives in docs/*.md. Never evaluate document contents.
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const target = path.join(root, "miniprogram/pages/agreement/documents.js");

function segments(text) {
  // Only the supplied documents' bold and URL notation is interpreted.
  // Everything else stays literal text, including any HTML or instructions.
  return text.replace(/<(https?:\/\/[^<>\s]+)>/g, "$1")
    .split(/(\*\*[^*]+\*\*)/g)
    .filter(Boolean)
    .map((part, id) => part.startsWith("**") && part.endsWith("**")
      ? { id, text: part.slice(2, -2), bold: true }
      : { id, text: part, bold: false });
}

function document(filename) {
  const source = fs.readFileSync(path.join(root, "docs", filename), "utf8")
    .replace(/^\uFEFF/, "").replace(/\r\n/g, "\n").trim();
  const paragraphs = source.split(/\n\s*\n/);
  const title = paragraphs.shift();
  if (!/^# [^\n]+$/.test(title)) throw new Error(filename + " requires a document title");
  const blocks = paragraphs.map((paragraph, id) => {
    let kind = "paragraph", text = paragraph;
    const heading = /^(#{2,6}) (.+)$/.exec(paragraph);
    if (heading) {
      kind = "heading-" + heading[1].length;
      text = heading[2];
    } else if (/^(最新修改日期|版本生效日期)：/.test(paragraph)) {
      kind = "date";
    } else if (paragraph.startsWith("> ")) {
      kind = "quote";
      text = paragraph.replace(/^> ?/gm, "");
    }
    return { id, kind, segments: segments(text) };
  });
  return { title: title.slice(2), blocks };
}

const output = "// Generated by npm run agreements:build from docs/*.md. Do not edit.\n"
  + "module.exports = " + JSON.stringify({
    user: document("用户协议.md"),
    privacy: document("隐私协议.md"),
  }, null, 2) + ";\n";

if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== output) throw new Error("Agreement text is stale. Run npm run agreements:build.");
  console.log("Agreement text matches both source documents.");
} else {
  fs.writeFileSync(target, output, "utf8");
  console.log("Built both agreement documents.");
}
