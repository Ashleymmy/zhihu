test('dispute resolution invalidates prior financial review and creator trace hides other payouts',async()=>{
 const f=await fixture(),creator=await f.login('creator'),admin=await f.login('admin')
 await f.store.put('keywords','50',{id:'50',...scope,bindingId:'60'})
 await f.store.put('bindings','60',{id:'60',keywordId:'50',leaderId:'2',executorId:'3',verificationStatus:'passed'})
 await f.store.put('facts','fact',{id:'fact',...scope,date:'2026-09-01',version:'v1',bindingId:'60',allocations:[{userId:'2',amount:'1'},{userId:'3',amount:'2'}],priceIds:['private']})
 const trace=await f.call(creator,'GET','/modules/zhihu/attributions/fact/trace',scope)
 assert.equal(trace.code,0);assert.equal(trace.data.fact.allocations.length,1);assert.equal(trace.data.fact.priceIds,undefined)
 const result=await f.call(creator,'POST','/modules/zhihu/evidence-bindings/60/dispute',{...scope,resolve:false,reason:'attribution incorrect',requestKey:'dispute-open-001'})
 assert.equal(result.code,0);assert.notEqual((await f.store.get('facts','fact')).version,'v1')
 assert.equal((await f.call(creator,'POST','/modules/zhihu/evidence-bindings/60/dispute',{...scope,resolve:true,reason:'fixed',requestKey:'dispute-resolve-001'})).statusCode,403)
 assert.equal((await f.call(admin,'POST','/modules/zhihu/evidence-bindings/60/dispute',{...scope,resolve:true,reason:'fixed',requestKey:'dispute-resolve-002'})).code,0)
})
