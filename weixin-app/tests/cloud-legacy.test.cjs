const test=require('node:test'),assert=require('node:assert/strict')
const {fixture,scope}=require('./cloud-fixture.cjs'),d=require('../cloudfunctions/opc-api/lib/domain')
test('historical withdrawals preserve cents, reserve atomically and retain two-stage review',async()=>{
 const f=await fixture(),creator=await f.login('creator'),leader=await f.login('leader'),admin=await f.login('admin')
 await f.store.put('legacy_earnings','1',{id:'1',userId:'3',projectId:'1',amount:'10000.0000',status:'confirmed'})
 const data={amount:'8000',settleType:'personal',payMethod:'wechat',payAccount:'test'}
 const responses=await Promise.all(['legacy-withdraw-001','legacy-withdraw-002'].map(requestKey=>f.call(creator,'POST','/modules/zhihu/withdrawals',{...data,requestKey})))
 assert.equal(responses.filter(r=>r.code===0).length,1);const id=responses[0].data.id
 assert.equal((await f.store.get('legacy_withdrawals',id)).amountYuan,'80.0000')
 assert.equal((await f.call(admin,'POST','/modules/zhihu/withdrawals/'+id+'/decide',{action:'approve',requestKey:'legacy-decide-001'})).statusCode,409)
 assert.equal((await f.call(leader,'POST','/modules/zhihu/withdrawals/'+id+'/review',{action:'approve',requestKey:'legacy-review-001'})).code,0)
 assert.equal((await f.call(admin,'POST','/modules/zhihu/withdrawals/'+id+'/decide',{action:'approve',requestKey:'legacy-decide-002'})).code,0)
 assert.equal((await f.store.get('legacy_withdrawals',id)).status,'approved')
 assert.equal((await f.call(creator,'POST','/modules/zhihu/withdrawals',{...data,requestKey:'legacy-withdraw-001'})).data.id,id)
})
